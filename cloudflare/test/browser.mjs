import assert from "node:assert/strict";
import { chromium } from "@playwright/test";
import { resolve } from "node:path";
export async function browserSmoke(base, evidence) {
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[], writes=[];
    page.on("pageerror", error=>errors.push(error.message));
    page.on("request", request=>{if(request.method()==="POST")writes.push(request.url());});
    await page.goto(base,{waitUntil:"networkidle"});
    await page.waitForFunction(()=>document.querySelectorAll("#action option").length===17);
    for(const id of ["searchInput","searchBtn","cartList","cartPrompt","copyCartPrompt","stats","names","auctions","offers","history","balances","handoff"]) assert.equal(await page.locator(`#${id}`).count(),1,id);
    await page.waitForFunction(()=>document.querySelectorAll("#ideasStrip .ideas-row").length===3 && document.querySelectorAll("#ideasStrip .idea").length>=12);
    assert.equal(await page.locator("#ideasStrip .ideas-row").count(),3);
    assert.equal(await page.locator("#siteTitle .title-glyph").count(),10);
    assert.match(await page.locator("#names").innerText(),/nexus/);
    assert.equal(await page.locator("#action option").count(),17);
    assert.ok((await page.locator("#stats").innerText()).length>10);
    const idea=page.locator("#ideasStrip .idea").first(); const ideaName=await idea.getAttribute("data-query");
    await idea.click();
    assert.equal(await page.locator("#searchInput").inputValue(),ideaName);
    assert.match(await page.locator("#ideasStatus").innerText(),/Added/);
    assert.equal(await page.locator("#cartCount").innerText(),"1");
    await page.locator("#searchInput").fill("quantum"); await page.locator("#searchBtn").click();
    await page.locator("#addToCartBtn").waitFor();
    await page.locator("#addToCartBtn").click();
    assert.equal(await page.locator("#cartCount").innerText(),"2");
    const prompt=await page.locator("#cartPrompt").innerText();
    for(const needle of ["keygen"," act ","submit_intent","quantum"]) assert.ok(prompt.includes(needle),needle);
    assert.equal(await page.locator("#copyCartPrompt").isEnabled(),true);
    assert.equal(await page.locator("#sectionTabs").count(),1);
    assert.equal(await page.locator("#marketSection").count(),1);
    assert.equal(await page.locator("#domainMain").count(),1);
    await page.goto(base + "/d/nexus",{waitUntil:"networkidle"});
    await page.waitForFunction(()=>document.querySelector("#domainTitle") && document.querySelector("#domainTitle").textContent.includes("nexus"));
    assert.match(await page.locator("#domainStatus").innerText(), /Owned|For sale|Auction|Available|Leased|Reserved/i);
    await page.goto(base,{waitUntil:"networkidle"});
    assert.equal(await page.locator("#floatingCartBtn").count(),1);
    assert.equal(await page.locator("#liveTicker").count(),1);
    assert.ok((await page.locator("#liveTickerTrack .ticker-chip").count()) + (await page.locator("#liveTickerTrack .ticker-empty").count()) >= 1);
    assert.equal(await page.locator(".auction-tab").count(),3);
    await page.locator("#floatingCartBtn").click();
    assert.equal(await page.locator("#floatingCartPanel").isVisible(),true);
    assert.equal(await page.locator("#copyCheckoutBtn").isEnabled(),true);
    await page.locator("#floatingCartBackdrop").click();
    assert.equal(await page.locator("#floatingCartPanel").isVisible(),false);
    await page.locator("#floatingCartBtn").click();
    await page.keyboard.press("Escape");
    assert.equal(await page.locator("#floatingCartPanel").isVisible(),false);
    await page.locator('.auction-tab[data-auction-tab="past"]').click();
    await page.locator('.auction-tab[data-auction-tab="current"]').click();
    await page.locator("#searchInput").fill("openai"); await page.locator("#searchBtn").click();
    assert.match(await page.locator("#searchResult").innerText(),/RESERVED/i);
    await page.evaluate(()=>document.fonts.ready);
    assert.equal(await page.locator("#error").innerText(),"");
    assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
    await page.locator("#floatingCartBtn").click();
    assert.equal(await page.locator("#floatingCartPanel").isVisible(),true);
    await page.screenshot({path:resolve(evidence,"browser.png"),fullPage:true});
    return {actionOptions:17,ideaRows:3,cartPrompt:true,pageErrors:errors,browserWrites:writes};
  } finally {await browser.close();}
}
